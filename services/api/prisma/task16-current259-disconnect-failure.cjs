const proofs=new WeakMap(), details=new WeakSet();
const own=(value,key)=>value&&typeof value==='object'&&!types.isProxy(value)
 ?Object.getOwnPropertyDescriptor(value,key)?.value:undefined;

function describeCurrent259DisconnectFailure(error){return proofs.get(error);}
function captureCurrent259DisconnectFailure(error,stage){
 const codeField=own(error,'code');
 // Only the fixed environment wrapper retains a cause. Read its private
 // diagnostic brand and never project the cause object or its properties.
 const existing=describeCurrent259DisconnectFailure(error)??(codeField==='CURRENT259_APP_ENV_CLEANUP_UNKNOWN'?
  describeCurrent259DisconnectFailure(own(error,'cause')):undefined);
 if(existing)return existing;
 if(!stages.has(stage))throw new Error('CURRENT259_DISCONNECT_DIAGNOSTIC_STAGE');
 const code=[codeField,own(error,'message')].find(value=>codes.has(value))??'CURRENT259_DISCONNECT_STAGE_FAILED';
 const detail=Object.freeze({stage,code});details.add(detail);return detail;
}
function carryCurrent259DisconnectFailure(error,detail){
 if(!details.has(detail))throw new Error('CURRENT259_DISCONNECT_DIAGNOSTIC_DETAIL');
 if(error&&typeof error==='object'&&!types.isProxy(error)&&!proofs.has(error))proofs.set(error,detail);
 return error;
}
module.exports=Object.freeze({describeCurrent259DisconnectFailure,captureCurrent259DisconnectFailure,carryCurrent259DisconnectFailure});
