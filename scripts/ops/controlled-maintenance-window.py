#!/usr/bin/env python3
"""Bounded OS write-source hold. DB/COS fences are separate, never implied.

Production CLI requires root, a fixed private plan digest and exact confirmation.
No credentials, network requests, database commands or service starts here.
"""
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import subprocess
import sys
import time

UNITS = ('jiangkong-api.service', 'jiangkong-draft-retention.service',
         'jiangkong-draft-retention.timer',
         'jiangkong-pristine-draft-deletion-receipt-purge.service',
         'jiangkong-pristine-draft-deletion-receipt-purge.timer')
CRON_PATHS = ('/var/spool/cron/crontabs/root', '/etc/cron.d/jiangkong-offsite-db-backup')
SHA = re.compile(r'^[a-f0-9]{64}$')

def digest(raw):
    return hashlib.sha256(raw).hexdigest()

def fingerprint(s):
    return (s.st_dev,s.st_ino,s.st_size,s.st_uid,s.st_gid,s.st_mode,s.st_nlink,s.st_mtime_ns,s.st_ctime_ns)

def read_regular(path, private=False):
    fd=os.open(path,os.O_RDONLY|os.O_NOFOLLOW)
    try:
        before=os.fstat(fd)
        if not stat.S_ISREG(before.st_mode) or before.st_nlink!=1 or before.st_mode&0o022 or before.st_size>2097152:raise ValueError('unsafe control file')
        if private and (before.st_uid!=os.getuid() or before.st_mode&0o077):raise ValueError('unsafe private file')
        with os.fdopen(os.dup(fd),'rb') as stream:raw=stream.read(2097153)
        if len(raw)>2097152 or fingerprint(before)!=fingerprint(os.fstat(fd)) or fingerprint(before)!=fingerprint(os.lstat(path)):raise ValueError('control file changed during read')
        return raw,{'uid':before.st_uid,'gid':before.st_gid,'mode':stat.S_IMODE(before.st_mode),'identity':fingerprint(before)}
    finally:os.close(fd)

def private_file(path):
    return read_regular(path,private=True)[0]

def root_cron_matches(source, logical):
    if source==logical:return True
    lines=source.splitlines(keepends=True)
    # Debian's spool adds these three comments; `crontab -l` omits them.
    return len(lines)>=3 and lines[0].startswith(b'# DO NOT EDIT THIS FILE - edit the master and reinstall.') and lines[1].startswith(b'# (') and b'installed on' in lines[1] and lines[2].startswith(b'# (Cron version') and b''.join(lines[3:])==logical

def validate_plan(plan):
    if set(plan) != {'candidateSha', 'runId', 'machineIdentitySha256', 'cronBindings'}:
        raise ValueError('invalid plan fields')
    if not re.fullmatch(r'[a-f0-9]{40}', plan['candidateSha']) or not re.fullmatch(r'[a-z0-9-]{1,60}', plan['runId']):
        raise ValueError('invalid version or run')
    if not SHA.fullmatch(plan['machineIdentitySha256']):
        raise ValueError('invalid machine identity')
    bindings = plan['cronBindings']
    if set(bindings) != set(CRON_PATHS) or sum(len(b['commandSha256']) for b in bindings.values()) != 3:
        raise ValueError('exact three cron bindings required')
    for b in bindings.values():
        if set(b) != {'fileSha256', 'commandSha256'} or not SHA.fullmatch(b['fileSha256']) or len(set(b['commandSha256'])) != len(b['commandSha256']) or not all(SHA.fullmatch(v) for v in b['commandSha256']):
            raise ValueError('invalid cron bindings')
    return json.loads(json.dumps(plan))

def isolate_cron(raw, commands, system_file, run):
    """Preserve every unmatched byte and all three original lines as comments."""
    out = []
    found = []
    for line in raw.splitlines(keepends=True):
        text = line.decode('utf-8').strip()
        if text and not text.startswith('#'):
            fields = text.split(None, 6 if system_file else 5)
            if len(fields) == (7 if system_file else 6):
                command = fields[-1]
                pin = digest(command.encode())
                if pin in commands:
                    if system_file and fields[5] != 'root':
                        raise ValueError('cron executor mismatch')
                    found.append(pin)
                    out.append(b'# controlled-launch:' + run.encode() + b' ' + line)
                    continue
        out.append(line)
    if sorted(found) != sorted(commands):
        raise ValueError('cron binding missing or repeated')
    return b''.join(out)

def assert_all_frozen(raw):
    values = {}
    for line in raw.decode('utf-8').splitlines():
        m = re.fullmatch(r'(OPERATIONAL_WRITE_FREEZE_MODE|OPERATIONAL_WRITE_FREEZE_MODULES)=(.*)', line)
        if not m:
            continue
        if m[1] in values:
            raise ValueError('duplicate freeze setting')
        value = m[2]
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[m[1]] = value
    if values.get('OPERATIONAL_WRITE_FREEZE_MODE') != 'all' or values.get('OPERATIONAL_WRITE_FREEZE_MODULES', '') != '':
        raise ValueError('all freeze required')

def atomic_write(path, raw, mode=0o600, uid=0, gid=0):
    path = Path(path)
    temp = path.with_name(path.name + '.controlled-new')
    fd = os.open(temp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, mode)
    try:
        os.fchmod(fd, mode)
        if os.getuid() == 0:
            os.fchown(fd, uid, gid)
        with os.fdopen(os.dup(fd), 'wb') as stream:
            stream.write(raw); stream.flush(); os.fsync(stream.fileno())
        os.replace(temp, path)
        parent = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try: os.fsync(parent)
        finally: os.close(parent)
    finally:
        os.close(fd)
        # On uncertain failure keep the temp file; never reuse or blindly delete.

class Window:
    def __init__(self, plan, command, read, write, state_dir, control_root):
        self.plan = validate_plan(plan)
        self.command, self.read, self.write = command, read, write
        self.state = Path(state_dir)
        self.control_root = control_root

    def save(self, journal):
        atomic_write(self.state / 'journal.json', json.dumps(journal, sort_keys=True, indent=2).encode() + b'\n')

    def load(self):
        journal = json.loads(private_file(self.state / 'journal.json'))
        self.validate_journal(journal)
        return journal

    def validate_journal(self,journal):
        if journal['planSha256'] != digest(json.dumps(self.plan, sort_keys=True).encode()):
            raise ValueError('journal plan changed')
        expected=set(CRON_PATHS)|{'/run/systemd/system/'+u+'.d/90-jiangkong-controlled-hold.conf'for u in UNITS}
        records=journal['records']
        if len(records)!=7 or {row['path']for row in records}!=expected:raise ValueError('journal targets incomplete or unknown')
        for row in records:
            after=bytes.fromhex(row['after'])
            if digest(after)!=row['afterSha256']:raise ValueError('journal after digest changed')
            if row['path'] in CRON_PATHS:
                before=bytes.fromhex(row['before']);source=bytes.fromhex(row['sourceBefore'])
                if digest(before)!=row['beforeSha256'] or digest(source)!=self.plan['cronBindings'][row['path']]['fileSha256']:raise ValueError('journal before digest changed')
                is_root=row['path'].endswith('/root')
                if (is_root and not root_cron_matches(source,before)) or (not is_root and source!=before):raise ValueError('journal cron source mismatch')
                derived=isolate_cron(before,self.plan['cronBindings'][row['path']]['commandSha256'],not is_root,self.plan['runId'])
            else:
                if row['before'] is not None:raise ValueError('unexpected previous hold file')
                unit=row['path'].split('/')[-2][:-2]
                derived=('[Unit]\nConditionPathExists='+self.control_root+'/'+self.plan['runId']+'/'+unit+'.allow\n').encode()
            if after!=derived:raise ValueError('journal hold is not plan-derived')

    def capture(self):
        # No change until both source files and logical root crontab are bound.
        records = []
        for path, binding in self.plan['cronBindings'].items():
            raw, meta = self.read(path)
            source=raw
            if digest(raw) != binding['fileSha256']:
                raise ValueError('cron source drift')
            if path.endswith('/root'):
                raw = self.command(['crontab', '-u', 'root', '-l'])
                if self.read(path)[0]!=source or not root_cron_matches(source,raw):raise ValueError('root crontab changed between reads')
            after = isolate_cron(raw, binding['commandSha256'], not path.endswith('/root'), self.plan['runId'])
            records.append({'path': path, 'sourceBefore':source.hex(),'before': raw.hex(), 'beforeSha256': digest(raw), 'after': after.hex(), 'afterSha256': digest(after), 'meta': meta})
        for unit in UNITS:
            path = '/run/systemd/system/' + unit + '.d/90-jiangkong-controlled-hold.conf'
            try: self.read(path)
            except FileNotFoundError: pass
            else: raise ValueError('existing hold file refused')
            allow = self.control_root + '/' + self.plan['runId'] + '/' + unit + '.allow'
            try: self.read(allow)
            except FileNotFoundError: pass
            else: raise ValueError('unexpected start allowance')
            body = ('[Unit]\nConditionPathExists=' + allow + '\n').encode()
            records.append({'path': path, 'before': None, 'after': body.hex(), 'afterSha256': digest(body), 'meta': {'uid': 0, 'gid': 0, 'mode': 0o644}})
        self.state.mkdir(mode=0o700)  # never reuse a run
        journal = {'planSha256': digest(json.dumps(self.plan, sort_keys=True).encode()), 'state': 'captured', 'records': records, 'completed': [], 'dbCosFreezeVerified': False}
        self.save(journal)
        return journal

    def current(self, row):
        if row['path'].endswith('/crontabs/root'):
            return self.command(['crontab', '-u', 'root', '-l'])
        try: return self.read(row['path'])[0]
        except FileNotFoundError: return None

    def hold(self):
        journal = self.load()
        if journal['state'] != 'captured': raise ValueError('run cannot be repeated')
        for row in journal['records']:
            expected = None if row['before'] is None else bytes.fromhex(row['before'])
            if self.current(row) != expected: raise ValueError('source changed after capture')
        journal['state'] = 'holding'; self.save(journal)
        # Stop future starts before requesting any drain. Cron paused first.
        for row in journal['records']:
            raw = bytes.fromhex(row['after'])
            if row['path'].endswith('/crontabs/root'):
                self.command(['crontab', '-u', 'root', '-'], raw)
            else:
                self.write(row['path'], raw, row['meta'])
            if self.current(row) != raw: raise ValueError('hold readback mismatch')
            journal['completed'].append(row['path']); self.save(journal)
        self.command(['systemctl', 'daemon-reload'])
        # timers first; no start/restart or signal escalation on failure
        for unit in sorted(UNITS, key=lambda u: not u.endswith('.timer')):
            self.command(['systemctl', 'stop', unit])
            self.assert_drained(unit)
        journal['state'] = 'os-sources-held'; self.save(journal)
        self.observe()
        return journal

    def assert_drained(self, unit):
        properties = 'ActiveState' if unit.endswith('.timer') else 'ActiveState,MainPID,ControlPID,ControlGroup,KillMode'
        values = self.command(['systemctl', 'show', unit, '--property=' + properties]).decode()
        props = dict(line.split('=', 1) for line in values.splitlines() if '=' in line)
        if props.get('ActiveState') != 'inactive': raise ValueError('unit not drained')
        if unit.endswith('.timer'): return
        if props.get('MainPID') != '0' or props.get('ControlPID') != '0' or props.get('KillMode') != 'control-group': raise ValueError('process drain unproven')
        group = props.get('ControlGroup')
        expected = '/system.slice/' + unit
        if group not in ('', expected): raise ValueError('unexpected control group')
        try: procs = self.read('/sys/fs/cgroup' + expected + '/cgroup.procs')[0]
        except FileNotFoundError: procs = b''
        if procs.strip(): raise ValueError('child processes remain')

    def observe(self,journal=None):
        journal = self.load() if journal is None else journal
        self.validate_journal(journal)
        preview=journal['state']=='api-preview-allowed'
        if not preview and journal['state'] != 'os-sources-held': raise ValueError('hold incomplete')
        for row in journal['records']:
            if self.current(row) != bytes.fromhex(row['after']): raise ValueError('hold drift')
        for unit in UNITS:
            allow = self.control_root + '/' + self.plan['runId'] + '/' + unit + '.allow'
            if preview and unit=='jiangkong-api.service':
                if self.read(allow)[0]!=(self.plan['candidateSha']+':'+self.plan['runId']+'\n').encode():raise ValueError('preview allowance changed')
                actual=self.command(['systemctl','show',unit,'--property=ActiveState']).decode().strip()
                if actual not in ('ActiveState=inactive','ActiveState=active'):raise ValueError('preview unit unstable')
                continue
            try: self.read(allow)
            except FileNotFoundError: pass
            else: raise ValueError('unexpected start allowance')
            self.assert_drained(unit)
        return journal

    def allow_api_preview(self):
        journal=self.observe()
        path=self.control_root+'/'+self.plan['runId']+'/jiangkong-api.service.allow'
        self.write(path,(self.plan['candidateSha']+':'+self.plan['runId']+'\n').encode(),{'uid':0,'gid':0,'mode':0o600})
        journal['state']='api-preview-allowed';self.save(journal)
        self.observe()
        return journal

    def end_api_preview(self):
        journal=self.observe()
        if journal['state']!='api-preview-allowed':raise ValueError('no owned preview')
        self.command(['systemctl','stop','jiangkong-api.service']);self.assert_drained('jiangkong-api.service')
        path=self.control_root+'/'+self.plan['runId']+'/jiangkong-api.service.allow'
        self.write(path,None,{'uid':0,'gid':0,'mode':0o600})
        journal['state']='os-sources-held';self.save(journal);self.observe()
        return journal

    def restore_controls(self, journal_pin):
        raw,identity=read_regular(self.state / 'journal.json',private=True)
        if not SHA.fullmatch(journal_pin) or digest(raw) != journal_pin: raise ValueError('rollback journal mismatch')
        journal = self.observe(json.loads(raw))  # inspect the approved bytes only
        if journal['state']!='os-sources-held':raise ValueError('end preview before restoring controls')
        current,current_identity=read_regular(self.state / 'journal.json',private=True)
        if current!=raw or current_identity!=identity: raise ValueError('journal changed')
        journal['state'] = 'restoring-controls'; self.save(journal)
        # This explicit operation resumes backup schedules, never starts API or
        # timers. It requires distinct approval; never called on hold failure.
        for row in journal['records']:
            if row['before'] is None:
                self.write(row['path'], None, row['meta'])
            elif row['path'].endswith('/crontabs/root'):
                self.command(['crontab', '-u', 'root', '-'], bytes.fromhex(row['before']))
            else:
                self.write(row['path'], bytes.fromhex(row['before']), row['meta'])
            journal['completed'].append('restored:' + row['path']); self.save(journal)
        self.command(['systemctl', 'daemon-reload'])
        for unit in UNITS: self.assert_drained(unit)
        journal['state'] = 'controls-restored-services-still-stopped'; self.save(journal)
        return journal

def main():
    operation, plan_path, plan_pin, *extra = sys.argv[1:]
    if operation not in ('capture', 'hold', 'observe', 'restore-controls','allow-api-preview','end-api-preview') or not SHA.fullmatch(plan_pin): raise ValueError('invalid operation')
    if (operation == 'restore-controls' and len(extra) != 1) or (operation != 'restore-controls' and extra): raise ValueError('invalid extra arguments')
    if os.getuid() != 0: raise ValueError('root required')
    raw = private_file(plan_path)
    if digest(raw) != plan_pin: raise ValueError('plan digest mismatch')
    plan = validate_plan(json.loads(raw))
    if os.environ.get('CONTROLLED_WINDOW_CONFIRM') != operation + ':' + plan_pin: raise ValueError('stage approval required')
    if digest(Path('/etc/machine-id').read_bytes().strip()) != plan['machineIdentitySha256']: raise ValueError('machine mismatch')
    assert_all_frozen(private_file('/etc/jiangkong/api.env'))
    started = time.monotonic(); deadline = 120 if operation == 'hold' else 30
    def command(argv, payload=None):
        remain = deadline - (time.monotonic() - started)
        if remain <= 0: raise ValueError('stage timeout')
        result = subprocess.run(argv, input=payload, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=min(remain, 90), check=False)
        if result.returncode or len(result.stdout) > 262144: raise ValueError('command stopped')
        return result.stdout
    def read(path):
        return read_regular(path)
    def write(path, body, meta):
        parent = Path(path).parent
        parent.mkdir(mode=0o755, parents=True, exist_ok=True)
        if str(parent.resolve()) != str(parent) or parent.stat().st_mode & 0o022: raise ValueError('unsafe parent')
        if body is None:
            os.unlink(path)
        else:
            atomic_write(path, body, meta['mode'], meta['uid'], meta['gid'])
    state_parent = Path('/var/lib/jiangkong-controlled-launch')
    state_parent.mkdir(mode=0o700, exist_ok=True)
    if str(state_parent.resolve()) != str(state_parent) or state_parent.stat().st_mode & 0o077: raise ValueError('unsafe state directory')
    window = Window(plan, command, read, write, state_parent / plan['runId'], '/run/jiangkong-controlled-launch')
    if operation != 'capture':
        private_file(window.state / 'journal.json')
    if operation == 'restore-controls': window.restore_controls(extra[0])
    else: getattr(window, operation.replace('-','_'))()
    print(json.dumps({'operation': operation, 'status': 'completed', 'dbCosFreezeVerified': False, 'serviceStarted': False}))

if __name__ == '__main__':
    try: main()
    except Exception:
        print('Controlled maintenance stage stopped; retain private journal and partial holds. No retry or service start.', file=sys.stderr)
        sys.exit(1)
