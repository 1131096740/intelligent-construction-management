import { writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { expect, test } from "@playwright/test";

test("真实新建、独立业务类型、手选已发布Word模板并保存生成实际文件", async ({ page, isMobile }, testInfo) => {
  const input = JSON.parse(process.env.TASK09_NEW_SELECTION_INPUT ?? "{}");
  await page.goto("/login?redirect=" + encodeURIComponent("/合同工作台/新建"));
  await page.getByPlaceholder("请输入手机号").fill(input.staff.phone);
  await page.getByPlaceholder("请输入密码").fill(input.staff.password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await expect(page.getByRole("heading", { name: "新建合同", exact: true })).toBeVisible();
  await page.getByPlaceholder("选择业务类型", { exact: true }).click();
  await page.getByText("材料采购", { exact: true }).last().click();
  await page.getByPlaceholder("可先留空，生成前选择", { exact: true }).click();
  await page.getByText("对上合同（我方公司与施工企业）", { exact: true }).last().click();
  const createdResponse = page.waitForResponse(response => response.request().method() === "POST" && response.url().endsWith("/api/contracts"));
  await page.getByRole("button", { name: "创建草稿", exact: true }).click();
  const created = await createdResponse;
  expect(created.status()).toBe(201);
  const draft = await created.json();
  const login = await page.request.post("/api/auth/login", { data: input.staff });
  expect(login.status()).toBe(201);
  const headers = { authorization: `Bearer ${(await login.json()).tokens.accessToken}`, "x-contract-numeric-protocol": "2" };
  await expect(page.getByText("待补充（未提交草稿）", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "基础信息", exact: true }).click();
  const name = page.getByPlaceholder("请填写合同名称", { exact: true });
  await name.scrollIntoViewIfNeeded();
  if (isMobile) await name.tap(); else await name.click();
  await expect(name).toBeFocused();
  await name.fill(`新建手选${testInfo.project.name}实际合同`); await name.blur();
  const basic = page.locator('[data-section-id="basic"]');
  await basic.getByPlaceholder("请填写业务类型", { exact: true }).click();
  await page.getByText("其他", { exact: true }).last().click();
  const parties = page.locator('[data-section-id="parties"] .party-form');
  await page.getByRole("link", { name: "合同主体", exact: true }).click();
  await parties.getByText("合同角色", { exact: true }).locator("..").locator(".t-select").click();
  await page.getByText("甲方", { exact: true }).last().click();
  await parties.getByPlaceholder("请输入公司名称", { exact: true }).fill("新建当前甲方");
  await parties.getByRole("button", { name: "加入合同草稿", exact: true }).click();
  await parties.getByPlaceholder("请输入公司名称", { exact: true }).fill("新建当前乙方");
  await parties.getByRole("button", { name: "加入合同草稿", exact: true }).click();
  await expect.poll(async () => (await (await page.request.get(`/api/contract-drafts/${draft.version.id}/workbench`, { headers })).json()).parties.length).toBe(2);
  await page.getByRole("link", { name: "合同文档", exact: true }).click();
  const selector = page.locator(".document-controls").getByPlaceholder("选择已发布版式", { exact: true });
  await expect(selector).toBeEnabled(); await expect(selector).toHaveValue("");
  await expect(page.getByRole("button", { name: "生成合同文件", exact: true })).toBeDisabled();
  await selector.click();
  await expect(page.getByText("材料业务样张 · V1", { exact: true })).toHaveCount(0);
  const choiceSaved = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith(`/contract-drafts/${draft.version.id}`) && response.request().postDataJSON()?.draft?.layoutTemplateVersionId === input.other.id);
  await page.getByText("其他业务样张 · V1", { exact: true }).click();
  expect((await choiceSaved).status()).toBe(200);
  const read = await page.request.get(`/api/contract-drafts/${draft.version.id}/workbench`, { headers });
  expect(read.status()).toBe(200);
  expect(await read.json()).toMatchObject({ contract: { contractTypeKey: "material_purchase" }, version: { layoutTemplateVersionId: input.other.id, draftData: { contractBasics: { businessType: "other", relationship: "upward" } } } });
  const queuedResponse = page.waitForResponse(response => response.request().method() === "POST" && response.url().endsWith(`/contract-workbench/${draft.version.id}/documents`));
  await page.getByRole("button", { name: "生成合同文件", exact: true }).click();
  const queued = await queuedResponse; expect(queued.status()).toBe(201);
  await expect(page.locator(".document-row")).toContainText("状态 已生成");
  const outputs = await (await page.request.get(`/api/contract-workbench/${draft.version.id}/documents`, { headers })).json();
  const output = outputs.find((row: { status: string }) => row.status === "success");
  expect(output).toMatchObject({ layoutTemplateVersionId: input.other.id, docxFileId: expect.any(String), pdfFileId: expect.any(String) });
  const ticket = await page.request.post(`/api/files/${output.docxFileId}/download-ticket`, { headers, data: { confirmationPassword: input.staff.password, downloadReason: "核对新建手选合同实际正文" } });
  expect(ticket.status()).toBe(201);
  const download = await page.request.get("/api" + (await ticket.json()).downloadUrl); expect(download.status()).toBe(200);
  const docx = await download.body(); await writeFile(testInfo.outputPath("generated.docx"), docx);
  await writeFile(testInfo.outputPath("receipt.json"), JSON.stringify({ versionId: draft.version.id, output, docxPath: testInfo.outputPath("generated.docx"), docxSha256: createHash("sha256").update(docx).digest("hex"), pdfVisualGate: "FAILED (formal local renderer Chinese glyph failure); not asserted as usable PDF" }, null, 2));
});
