import {expect, test} from "@playwright/test";
test("keeping an unsaved note then confirming autosave clears the cached unsaved close warning", async ({page, request}) => {
  const session=await(await request.get("/api/__spot_fixture/session")).json();
  const headers={authorization:`Bearer ${session.accessToken}`};
  await request.post("/api/__spot_fixture/reset");
  const row=await(await request.post("/api/spot-procurements",{headers,data:{projectId:"spot-project",lines:[{materialName:"原材料"}]}})).json();
  await page.addInitScript(value=>localStorage.setItem("jiangkong-web-admin-auth",JSON.stringify(value)),session);
  await page.goto(`/零星采购/${row.procurementId}`);
  await page.locator(".t-tabs__nav-item-text-wrapper").filter({hasText:/^审批与动作$/}).click();
  await page.getByRole("button",{name:"编辑采购草稿",exact:true}).click();
  const saved=page.waitForResponse(response=>response.request().method()==="PATCH"&&response.url().endsWith(`/spot-procurements/${row.procurementId}/draft`));
  await page.getByLabel("备注（可选）",{exact:true}).fill("已经自动保存的备注");
  await page.getByLabel("备注（可选）",{exact:true}).press("Tab");
  await page.getByRole("button",{name:"取消",exact:true}).click();
  await expect(page.getByText("当前填写尚未保存",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"保留当前填写",exact:true}).click();
  expect((await saved).status()).toBe(200);
  await expect(page.getByText("已自动保存",{exact:true})).toBeVisible();
  const confirmed=await(await request.get(`/api/spot-procurements/${row.procurementId}`,{headers})).json();
  expect(confirmed.currentVersion.note).toBe("已经自动保存的备注");
  await page.getByRole("button",{name:"取消",exact:true}).click();
  await expect(page.getByTestId("spot-request-grid")).not.toBeVisible();
  await expect(page.getByText("当前填写尚未保存",{exact:true})).not.toBeVisible();
});

// Explicitly confirmed navigation driver: official exported router, real app,
