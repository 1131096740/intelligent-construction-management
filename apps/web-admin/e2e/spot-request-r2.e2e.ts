test("same-record public router navigation preserves B native buffer until explicit discard then loads A without cross-record writes", async ({page, request}) => {
  const session=await(await request.get("/api/__spot_fixture/session")).json();
  const headers={authorization:`Bearer ${session.accessToken}`}; await request.post("/api/__spot_fixture/reset");
  const create=async(materialName:string)=>(await(await request.post("/api/spot-procurements",{headers,data:{projectId:"spot-project",lines:[{materialName}]}})).json());
  const a=await create("甲单材料"), b=await create("乙单材料");
  await page.addInitScript(value=>localStorage.setItem("jiangkong-web-admin-auth",JSON.stringify(value)),session);
  await page.goto(`/零星采购/${a.procurementId}`);
  await page.locator(".t-tabs__nav-item-text-wrapper").filter({hasText:/^审批与动作$/}).click();
  await expect(page.getByRole("button",{name:"编辑采购草稿",exact:true})).toBeVisible();
  const document=await page.evaluateHandle(()=>window.document);
  await page.evaluate(async path=>{const modulePath="/src/routes/index.ts";const {router}=await import(modulePath);await router.isReady();await router.push(path);},`/零星采购/${b.procurementId}`);
  expect(await document.evaluate(previous=>previous===window.document)).toBe(true);
  await page.locator(".t-tabs__nav-item-text-wrapper").filter({hasText:/^审批与动作$/}).click();
  await page.getByRole("button",{name:"编辑采购草稿",exact:true}).click();
  const grid=page.getByTestId("spot-request-grid").locator("revo-grid");
  await grid.getByRole("gridcell",{name:"乙单材料",exact:true}).dblclick();
  const input=grid.locator("revogr-edit input");await input.fill("乙单中文未确认");
  const urlB=page.url();
  await page.evaluate(async path=>{const modulePath="/src/routes/index.ts";const {router}=await import(modulePath);await router.push(path);},`/零星采购/${a.procurementId}`);
  await expect(page).toHaveURL(urlB);
  await expect(page.getByText("当前填写尚未保存，请先确认单元格并保存，或关闭填写窗口后再离开",{exact:true})).toBeVisible();
  await expect(input).toHaveValue("乙单中文未确认");
  expect(await document.evaluate(previous=>previous===window.document)).toBe(true);
  await page.getByRole("button",{name:"取消",exact:true}).click();
  await page.getByRole("button",{name:"放弃未保存改动并关闭",exact:true}).click();
  await page.goBack();
  await expect(page).toHaveURL(new RegExp(`/${encodeURIComponent("零星采购")}/${a.procurementId}$`));
  await expect(page.getByTestId("spot-request-grid")).not.toBeVisible();
  await page.locator(".t-tabs__nav-item-text-wrapper").filter({hasText:/^审批与动作$/}).click();
  await page.getByRole("button",{name:"编辑采购草稿",exact:true}).click();
  await expect(grid.getByRole("gridcell",{name:"甲单材料",exact:true})).toBeVisible();
  const saved=page.waitForResponse(response=>response.request().method()==="PATCH"&&response.url().endsWith(`/spot-procurements/${a.procurementId}/draft`));
  await page.getByLabel("备注（可选）",{exact:true}).fill("只写甲单备注");expect((await saved).status()).toBe(200);
  await expect(page.getByText("已自动保存",{exact:true})).toBeVisible();
  const read=async(id:string)=>(await(await request.get(`/api/spot-procurements/${id}`,{headers})).json());
  expect((await read(a.procurementId)).lines[0].materialName).toBe("甲单材料");
  const unchangedB=await read(b.procurementId);expect(unchangedB.lines[0].materialName).toBe("乙单材料");expect(unchangedB.currentVersion.draftRevision).toBe(b.draftRevision);
  await document.dispose();
});

test("late confirmed B read cannot retain its editor or refill A after an allowed same-record switch", async ({page, request}) => {
  const session=await(await request.get("/api/__spot_fixture/session")).json();
  const headers={authorization:`Bearer ${session.accessToken}`};await request.post("/api/__spot_fixture/reset");
  const create=async(materialName:string)=>(await(await request.post("/api/spot-procurements",{headers,data:{projectId:"spot-project",lines:[{materialName}]}})).json());
  const a=await create("甲单独立材料"), b=await create("乙单独立材料");
  await page.addInitScript(value=>localStorage.setItem("jiangkong-web-admin-auth",JSON.stringify(value)),session);
  await page.goto(`/零星采购/${b.procurementId}`);
  await page.locator(".t-tabs__nav-item-text-wrapper").filter({hasText:/^审批与动作$/}).click();
  await page.getByRole("button",{name:"编辑采购草稿",exact:true}).click();
  await request.post("/api/__spot_fixture/hold-confirmation-read");
  const patched=page.waitForResponse(response=>response.request().method()==="PATCH"&&response.url().endsWith(`/spot-procurements/${b.procurementId}/draft`));
  await page.getByLabel("备注（可选）",{exact:true}).fill("已提交乙单备注");expect((await patched).status()).toBe(200);
  await expect.poll(async()=>(await(await request.get("/api/__spot_fixture/held-confirmation-read")).json()).pending).toBe(true);
  const oldRead=page.waitForResponse(response=>response.request().method()==="GET"&&response.url().endsWith(`/spot-procurements/${b.procurementId}`));
  await page.evaluate(async path=>{const modulePath="/src/routes/index.ts";const {router}=await import(modulePath);await router.isReady();await router.push(path);},`/零星采购/${a.procurementId}`);
  await expect(page).toHaveURL(new RegExp(`/${encodeURIComponent("零星采购")}/${a.procurementId}$`));
  await expect(page.getByTestId("spot-request-grid")).not.toBeVisible();
  await page.locator(".t-tabs__nav-item-text-wrapper").filter({hasText:/^审批与动作$/}).click();
  await page.getByRole("button",{name:"编辑采购草稿",exact:true}).click();
  const grid=page.getByTestId("spot-request-grid").locator("revo-grid");
  await expect(grid.getByRole("gridcell",{name:"甲单独立材料",exact:true})).toBeVisible();
  await request.post("/api/__spot_fixture/release-confirmation-read");expect((await oldRead).status()).toBe(200);
  await expect(grid.getByRole("gridcell",{name:"甲单独立材料",exact:true})).toBeVisible();
  await expect(page.getByLabel("备注（可选）",{exact:true})).toHaveValue("");
  const savedA=page.waitForResponse(response=>response.request().method()==="PATCH"&&response.url().endsWith(`/spot-procurements/${a.procurementId}/draft`));
  await page.getByLabel("备注（可选）",{exact:true}).fill("甲单之后独立保存");expect((await savedA).status()).toBe(200);
  await expect(page.getByText("已自动保存",{exact:true})).toBeVisible();
  const read=async(id:string)=>(await(await request.get(`/api/spot-procurements/${id}`,{headers})).json());
  const freshA=await read(a.procurementId), freshB=await read(b.procurementId);
  expect(freshA.lines[0].materialName).toBe("甲单独立材料");expect(freshA.currentVersion.note).toBe("甲单之后独立保存");
  expect(freshB.lines[0].materialName).toBe("乙单独立材料");expect(freshB.currentVersion.note).toBe("已提交乙单备注");
});
