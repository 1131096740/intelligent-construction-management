import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { expect, test } from "@playwright/test";

test("首次选择模板保存后刷新前能编辑当前完整正文", async ({ page }, testInfo) => {
  const input = JSON.parse(process.env.TASK10_BODY_BROWSER_INPUT ?? "{}");
  const draft = input.draft;
  const target = "/合同工作台/" + draft.contract.id + "?versionId=" + draft.version.id;
  await page.goto("/login?redirect=" + encodeURIComponent(target));
  await page.getByPlaceholder("请输入手机号").fill(input.staff.phone);
  await page.getByPlaceholder("请输入密码").fill(input.staff.password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.getByText("填写信息", { exact: true }).click();
  const navigation = page.getByRole("navigation", { name: "合同资料章节", exact: true });
  await navigation.getByRole("link", { name: "合同文档", exact: true }).click();
  const selector = page.locator(".document-controls").getByPlaceholder("选择已发布版式", { exact: true });
  await expect(selector).toBeEnabled();
  await expect(selector).toHaveValue("");
  const freshness = [];
  for (const file of ["src/pages/contracts/ContractWorkbenchPage.vue", "src/pages/contracts/workbench/ContractDocumentsSection.vue", "src/pages/contracts/workbench/ContractBodyEditor.vue", "src/pages/contracts/workbench/ContractBodyFlow.vue", "src/pages/contracts/workbench/use-contract-draft.ts"]) {
    const response = await page.request.get("/" + file);
    expect(response.status()).toBe(200);
    const bytes = await response.body();
    await writeFile(testInfo.outputPath(file.split("/").at(-1)! + ".served.js"), bytes);
    freshness.push({ file, diskSha256: createHash("sha256").update(await readFile(resolve(file))).digest("hex"), publicServedJavaScriptSha256: createHash("sha256").update(bytes).digest("hex") });
  }
  await writeFile(testInfo.outputPath("public-source-freshness.json"), JSON.stringify(freshness, null, 2));
  const login = await page.request.post("/api/auth/login", { data: input.staff });
  expect(login.status()).toBe(201);
  const headers = { authorization: "Bearer " + (await login.json()).tokens.accessToken, "x-contract-numeric-protocol": "2" };
  const base = "/api/contract-drafts/" + draft.version.id;
  const beforeResponse = await page.request.get(base + "/workbench", { headers });
  expect(beforeResponse.status()).toBe(200);
  const before = await beforeResponse.json();
  expect(before.version).toMatchObject({ numericProtocolVersion: 2, layoutTemplateVersionId: null, amountYuan: "6.5000" });
  expect(before.version.draftData.documentBody).toBeUndefined();
  expect(before.version.draftData.documentBodyAction).toBeUndefined();
  const selectedSave = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/contract-drafts/" + draft.version.id) && response.request().postDataJSON()?.draft?.layoutTemplateVersionId === input.layout.id);
  await selector.click();
  await page.getByText("首次选用材料合同 · V1", { exact: true }).click();
  const selected = await selectedSave;
  const payload = selected.request().postDataJSON();
  const text = await selected.text();
  await writeFile(testInfo.outputPath("public-first-selection-save-response.json"), JSON.stringify({ status: selected.status(), response: text, idempotencyKey: payload.idempotencyKey, expectedRevision: payload.expectedRevision, protocol: payload.draft?.numericProtocolVersion, layout: payload.draft?.layoutTemplateVersionId, actionPresent: Object.hasOwn(payload.draft?.draftData ?? {}, "documentBodyAction") }, null, 2));
  expect(payload.expectedRevision).toBe(before.version.draftRevision);
  expect(Object.hasOwn(payload.draft.draftData, "documentBodyAction")).toBe(false);
  expect(payload.draft.numericProtocolVersion).toBe(2);
  expect(selected.status()).toBe(200);
  const receipt = JSON.parse(text);
  const afterResponse = await page.request.get(base + "/workbench", { headers });
  expect(afterResponse.status()).toBe(200);
  const after = await afterResponse.json();
  expect(after.version).toMatchObject({ layoutTemplateVersionId: input.layout.id, draftRevision: receipt.serverRevision, amountYuan: "6.5000" });
  expect(after.version.draftData.documentBodyAction).toBeUndefined();
  const bodyResponse = await page.request.get(base + "/document-body", { headers });
  expect(bodyResponse.status()).toBe(200);
  const body = await bodyResponse.json();
  expect(body).toMatchObject({ layoutTemplateVersionId: input.layout.id, sourceSha256: input.sourceSha256, draftRevision: receipt.serverRevision });
  const ordinary = body.blocks.find((block: { editable: boolean; text: string }) => block.editable && block.text.startsWith("4.若卖方违背"));
  expect(ordinary).toBeDefined();
  await writeFile(testInfo.outputPath("public-after-first-selection.json"), JSON.stringify({ sourceSha256: body.sourceSha256, layoutTemplateVersionId: body.layoutTemplateVersionId, draftRevision: body.draftRevision, documentContentRevision: body.documentContentRevision, ordinary, amountYuan: after.version.amountYuan }, null, 2));
  // No reload or model injection before the first current-body editor check.
  await page.getByText("合同正文", { exact: true }).click();
  const editor = page.getByRole("region", { name: "完整合同正文", exact: true });
  await expect(editor).toBeVisible();
  const number = body.blocks.findIndex((block: { id: string }) => block.id === ordinary.id) + 1;
  const textarea = editor.getByRole("textbox", { name: "编辑普通条款" + number, exact: true });
  await expect(textarea).toHaveValue(ordinary.text);
  await expect(textarea).toBeEditable();
  await textarea.focus();
  await expect(textarea).toBeFocused();
  await expect(editor.getByRole("button", { name: "保存正文", exact: true })).toBeEnabled();
  const tables = editor.getByRole("region", { name: "合同正文表格", exact: true });
  await expect(tables).toHaveCount(2);
  const amount = tables.nth(0).getByRole("table").getByRole("row").nth(1).getByRole("cell").nth(7);
  await expect(amount).toHaveText("6.5000");
  await expect(amount.getByRole("textbox")).toHaveCount(0);
  const dimensions = await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth }));
  expect(dimensions.documentWidth).toBeLessThanOrEqual(dimensions.viewport + 1);
  await page.screenshot({ path: testInfo.outputPath("first-selected-body.png"), fullPage: true });
  await writeFile(testInfo.outputPath("receipt.json"), JSON.stringify({ sourceSha256: body.sourceSha256, layoutTemplateVersionId: body.layoutTemplateVersionId, draftRevision: body.draftRevision, dimensions, scope: "first no-regeneration template save normalACK then actualeditablebody beforeanyreload; no templatepublication/realPDF/queryACK" }, null, 2));
});
