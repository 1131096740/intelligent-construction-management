import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { expect, test } from "@playwright/test";

test("手动四位不含税金额加载后普通名称保存仍保持原值", async ({ page }, testInfo) => {
  const input = JSON.parse(process.env.TASK10_BODY_BROWSER_INPUT ?? "{}");
  const draft = input.draft;
  const target = "/合同工作台/" + draft.contract.id + "?versionId=" + draft.version.id;
  const initialPuts: string[] = [];
  page.on("request", request => {
    if (request.method() === "PUT" && request.url().endsWith("/contract-drafts/" + draft.version.id)) initialPuts.push(request.url());
  });
  await page.goto("/login?redirect=" + encodeURIComponent(target));
  await page.getByPlaceholder("请输入手机号").fill(input.staff.phone);
  await page.getByPlaceholder("请输入密码").fill(input.staff.password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.getByText("填写信息", { exact: true }).click();
  const navigation = page.getByRole("navigation", { name: "合同资料章节", exact: true });
  await navigation.getByRole("link", { name: "清单与税务", exact: true }).click();
  const sources = [];
  for (const file of ["src/pages/contracts/ContractWorkbenchPage.vue", "src/pages/contracts/workbench/use-contract-draft.ts", "src/pages/contracts/workbench/ContractPricingSection.vue", "src/pages/contracts/workbench/ContractBasicSection.vue"]) {
    const response = await page.request.get("/" + file);
    expect(response.status()).toBe(200);
    const bytes = await response.body();
    await writeFile(testInfo.outputPath(file.split("/").at(-1)! + ".served.js"), bytes);
    sources.push({ file, diskSha256: createHash("sha256").update(await readFile(resolve(file))).digest("hex"), publicServedJavaScriptSha256: createHash("sha256").update(bytes).digest("hex") });
  }
  await writeFile(testInfo.outputPath("public-source-freshness.json"), JSON.stringify(sources, null, 2));
  const login = await page.request.post("/api/auth/login", { data: input.staff });
  expect(login.status()).toBe(201);
  const headers = { authorization: "Bearer " + (await login.json()).tokens.accessToken, "x-contract-numeric-protocol": "2" };
  const response = await page.request.get("/api/contract-drafts/" + draft.version.id + "/workbench", { headers });
  expect(response.status()).toBe(200);
  const before = await response.json();
  expect(before.version).toMatchObject({ numericProtocolVersion: 2, pricingNature: "fixed_total", amountSource: "manual", amountYuan: "1.5340", invoiceType: null, defaultTaxRatePercent: null });
  expect(before.version.layoutTemplateVersionId ?? null).toBeNull();
  expect(before.version.draftRevision).toBe(input.expectedRevision);
  expect(before.version.draftData.contractBasics).toMatchObject({ businessType: "other", relationship: "upward", amountBasis: "tax_exclusive", invoiceStatus: "none" });
  expect(before.bills.every((bill: { rows: unknown[] }) => bill.rows.length === 0)).toBe(true);
  const basisDefinition = before.businessEntry.definition.fields.find((field: { key: string }) => field.key === "amountBasis");
  expect(basisDefinition).toMatchObject({ label: "金额口径", options: expect.arrayContaining([{ value: "tax_exclusive", label: "不含税" }]) });
  const pricing = page.locator('section[data-section-id="bill_tax"]');
  await expect(pricing.getByRole("heading", { name: "计价与金额", exact: true })).toBeVisible();
  await expect(pricing.getByText("不含税合同金额（元）", { exact: true })).toBeVisible();
  const amount = pricing.getByPlaceholder("请输入不含税合同金额，未知可留空", { exact: true });
  await expect(amount).toHaveCount(1);
  await expect(amount).toBeVisible();
  await expect(amount).toBeEditable();
  await writeFile(testInfo.outputPath("public-amount-load-before-target.json"), JSON.stringify({ publicVersion: { numericProtocolVersion: before.version.numericProtocolVersion, pricingNature: before.version.pricingNature, amountSource: before.version.amountSource, amountYuan: before.version.amountYuan, draftRevision: before.version.draftRevision, invoiceType: before.version.invoiceType, defaultTaxRatePercent: before.version.defaultTaxRatePercent }, contractBasics: before.version.draftData.contractBasics, actualInputValue: await amount.inputValue(), publicPUTCountBeforeTarget: initialPuts.length, scope: "fresh public saved manual amount is the authority; first target is visible input value, no body/composable private reads or money input edits" }, null, 2));
  await expect(amount).toHaveValue("1.5340");
  await navigation.getByRole("link", { name: "基础信息", exact: true }).click();
  const basic = page.locator('section[data-section-id="basic"]');
  const contractName = basic.getByRole("textbox", { name: /合同名称/u });
  await expect(contractName).toHaveCount(1);
  await expect(contractName).toBeEditable();
  await expect(contractName).toHaveValue("上游新建当前合同名称");
  const changedName = "手动净额保持原值";
  const savedResponse = page.waitForResponse(value => value.request().method() === "PUT" && value.url().endsWith("/contract-drafts/" + draft.version.id) &&
    value.request().postDataJSON()?.draft?.draftData?.contractName === changedName);
  await contractName.fill(changedName);
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  const savedResponseValue = await savedResponse;
  const payload = savedResponseValue.request().postDataJSON();
  const responseText = await savedResponseValue.text();
  await writeFile(testInfo.outputPath("public-nonamount-save-response.json"), JSON.stringify({ status: savedResponseValue.status(), response: responseText, idempotencyKey: payload.idempotencyKey, expectedRevision: payload.expectedRevision, numericProtocolVersion: payload.draft.numericProtocolVersion, pricingNature: payload.draft.pricingNature, amountSource: payload.draft.amountSource, manualAmountYuan: payload.draft.manualAmountYuan, hasLegacyManualAmountCents: Object.hasOwn(payload.draft, "manualAmountCents"), taxFacts: payload.draft.taxFacts, contractName: payload.draft.draftData.contractName }, null, 2));
  expect(payload.expectedRevision).toBe(before.version.draftRevision);
  expect(payload.draft).toMatchObject({ numericProtocolVersion: 2, pricingNature: "fixed_total", amountSource: "manual", manualAmountYuan: "1.5340" });
  expect(Object.hasOwn(payload.draft, "manualAmountCents")).toBe(false);
  expect(payload.draft.taxFacts).toMatchObject({ invoiceType: null, defaultTaxRatePercent: null });
  expect(savedResponseValue.status()).toBe(200);
  const receipt = JSON.parse(responseText);
  const reread = await page.request.get("/api/contract-drafts/" + draft.version.id + "/workbench", { headers });
  expect(reread.status()).toBe(200);
  const saved = await reread.json();
  expect(saved.version).toMatchObject({ numericProtocolVersion: 2, pricingNature: "fixed_total", amountSource: "manual", amountYuan: "1.5340", invoiceType: null, defaultTaxRatePercent: null, draftRevision: receipt.serverRevision });
  expect(saved.version.draftData.contractName).toBe(changedName);
  expect(saved.version.draftData.contractBasics.amountBasis).toBe("tax_exclusive");
  expect(saved.version.layoutTemplateVersionId ?? null).toBeNull();
  expect(saved.bills.every((bill: { rows: unknown[] }) => bill.rows.length === 0)).toBe(true);
  await page.reload();
  await page.getByText("填写信息", { exact: true }).click();
  await navigation.getByRole("link", { name: "清单与税务", exact: true }).click();
  await expect(amount).toHaveValue("1.5340");
  await expect(pricing.getByText("不含税合同金额（元）", { exact: true })).toBeVisible();
  const dimensions = await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth }));
  expect(dimensions.documentWidth).toBeLessThanOrEqual(dimensions.viewport + 1);
  await page.screenshot({ path: testInfo.outputPath("manual-net-amount-preserved.png"), fullPage: true });
  await writeFile(testInfo.outputPath("receipt.json"), JSON.stringify({ initialAmountYuan: before.version.amountYuan, savedAmountYuan: saved.version.amountYuan, changedName, numericProtocolVersion: saved.version.numericProtocolVersion, amountBasis: saved.version.draftData.contractBasics.amountBasis, unknownDefaultRate: saved.version.defaultTaxRatePercent, invoiceType: saved.version.invoiceType, draftRevision: saved.version.draftRevision, dimensions, scope: "one known manual four-decimal net amount fresh load/nonamount name save/reload; no amount filling, tax calculation, unknown/zero/legacy or multi-contract matrix" }, null, 2));
});
