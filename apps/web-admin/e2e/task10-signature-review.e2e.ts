import { expect, test } from "@playwright/test";

test("签署补充核对保存、修改失效并保留原文", async ({ page }, testInfo) => {
  const input = JSON.parse(process.env.TASK10_BODY_BROWSER_INPUT ?? "{}");
  const draft = input.drafts[testInfo.project.name];
  const path = `/contract-drafts/${draft.version.id}`;
  await page.goto("/login?redirect=" + encodeURIComponent(`/合同工作台/${draft.contract.id}?versionId=${draft.version.id}`));
  await page.getByPlaceholder("请输入手机号").fill(input.staff.phone);
  await page.getByPlaceholder("请输入密码").fill(input.staff.password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.getByText("合同正文", { exact: true }).click();
  const editor = page.getByRole("region", { name: "完整合同正文", exact: true });
  const notice = editor.getByRole("status", { name: "正文提示", exact: true });
  await expect(notice.getByText("乙方补充信息", { exact: true })).toBeVisible();
  await expect(notice.getByText("虚构乙方补充原文", { exact: true })).toBeVisible();
  const confirmation = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith(path) && Boolean(response.request().postDataJSON()?.draft?.draftData?.documentBody?.signatureSupplementReviewDigest));
  await notice.getByRole("button", { name: "已核对内容及甲乙方归属", exact: true }).click();
  await editor.getByRole("button", { name: "保存正文", exact: true }).click();
  expect((await confirmation).status()).toBe(200);
  await expect(notice.getByRole("button", { name: "已核对内容及甲乙方归属", exact: true })).toHaveCount(0);
  const login = await page.request.post("/api/auth/login", { data: input.staff });
  expect(login.status()).toBe(201);
  const headers = { authorization: `Bearer ${(await login.json()).tokens.accessToken}`, "x-contract-numeric-protocol": "2" };
  const bodyResponse = await page.request.get(`/api${path}/document-body`, { headers });
  expect(bodyResponse.status()).toBe(200);
  const body = await bodyResponse.json();
  expect(body.signatureSupplementReview.confirmed).toBe(true);
  const entry = body.signatureSupplementReview.entries.find((item: { text: string }) => item.text === "虚构乙方补充原文");
  expect(entry).toBeTruthy();
  const blockNumber = body.blocks.findIndex((item: { id: string }) => item.id === entry.id) + 1;
  expect(blockNumber).toBeGreaterThan(0);
  const text = editor.getByRole("textbox", { name: `编辑普通条款${blockNumber}`, exact: true });
  await expect(text).toHaveValue("虚构乙方补充原文");
  const changed = "虚构乙方补充原文（修改）";
  const saved = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith(path) && response.request().postDataJSON()?.draft?.draftData?.documentBody?.edits?.some((item: { text: string }) => item.text === changed));
  await text.fill(changed);
  await editor.getByRole("button", { name: "保存正文", exact: true }).click();
  expect((await saved).status()).toBe(200);
  await expect(notice.getByText(changed, { exact: true })).toBeVisible();
  await expect(notice.getByRole("button", { name: "已核对内容及甲乙方归属", exact: true })).toBeVisible();
  const reread = await page.request.get(`/api${path}/document-body`, { headers });
  const after = await reread.json();
  expect(after.signatureSupplementReview.confirmed).toBe(false);
  expect(after.signatureSupplementReview.entries).toEqual(expect.arrayContaining([expect.objectContaining({ id: entry.id, text: changed })]));
  const reconfirmed = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith(path) && response.request().postDataJSON()?.draft?.draftData?.documentBody?.signatureSupplementReviewDigest === after.signatureSupplementReview.digest);
  await notice.getByRole("button", { name: "已核对内容及甲乙方归属", exact: true }).click();
  await editor.getByRole("button", { name: "保存正文", exact: true }).click();
  expect((await reconfirmed).status()).toBe(200);
  await expect(notice.getByRole("button", { name: "已核对内容及甲乙方归属", exact: true })).toHaveCount(0);
  const finalRead = await page.request.get(`/api${path}/document-body`, { headers });
  const finalBody = await finalRead.json();
  expect(finalBody.signatureSupplementReview.confirmed).toBe(true);
  expect(finalBody.signatureSupplementReview.entries).toEqual(expect.arrayContaining([expect.objectContaining({ id: entry.id, text: changed })]));
});
