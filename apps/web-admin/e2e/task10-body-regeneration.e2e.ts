import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { expect, test } from "@playwright/test";

test("明确确认全量重新生成并保留重建前手工正文检查点", async ({ page }, testInfo) => {
  const input = JSON.parse(process.env.TASK10_BODY_BROWSER_INPUT ?? "{}");
  const draft = input.drafts[testInfo.project.name];
  const target = "/合同工作台/" + draft.contract.id + "?versionId=" + draft.version.id;
  await page.goto("/login?redirect=" + encodeURIComponent(target));
  await page.getByPlaceholder("请输入手机号").fill(input.staff.phone);
  await page.getByPlaceholder("请输入密码").fill(input.staff.password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.getByText("合同正文", { exact: true }).click();
  const editor = page.getByRole("region", { name: "完整合同正文", exact: true });
  await expect(editor).toBeVisible();
  await expect(editor.getByRole("button", { name: "保存正文", exact: true })).toBeEnabled();
  const sources = [];
  for (const file of ["src/pages/contracts/ContractWorkbenchPage.vue", "src/pages/contracts/workbench/ContractBodyEditor.vue", "src/pages/contracts/workbench/ContractBodyFlow.vue"]) {
    const response = await page.request.get("/" + file);
    expect(response.status()).toBe(200);
    const bytes = await response.body();
    await writeFile(testInfo.outputPath(file.split("/").at(-1)! + ".served.js"), bytes);
    sources.push({ file, diskSha256: createHash("sha256").update(await readFile(resolve(file))).digest("hex"), publicServedJavaScriptSha256: createHash("sha256").update(bytes).digest("hex") });
  }
  await writeFile(testInfo.outputPath("public-source-freshness.json"), JSON.stringify(sources, null, 2));
  const login = await page.request.post("/api/auth/login", { data: input.staff });
  expect(login.status()).toBe(201);
  const headers = { authorization: "Bearer " + (await login.json()).tokens.accessToken, "x-contract-numeric-protocol": "2" };
  const base = "/api/contract-drafts/" + draft.version.id;
  const workbenchResponse = await page.request.get(base + "/workbench", { headers });
  expect(workbenchResponse.status()).toBe(200);
  const workbench = await workbenchResponse.json();
  expect(workbench.version.numericProtocolVersion).toBe(2);
  expect(workbench.version.amountYuan).toBe("6.5000");
  const oldPlan = workbench.version.draftData.documentBody;
  expect(oldPlan.edits).toEqual([{ positionId: expect.any(String), text: draft.originalOrdinaryText + "原有人工条款需保留。" }]);
  expect(oldPlan.additions).toEqual([{ id: draft.additionId, afterPositionId: oldPlan.edits[0].positionId, text: "重新生成前已保存的新增约定。" }]);
  const beforeResponse = await page.request.get(base + "/document-body", { headers });
  expect(beforeResponse.status()).toBe(200);
  const before = await beforeResponse.json();
  expect(before.sourceSha256).toBe(input.sourceSha256);
  expect(before.layoutTemplateVersionId).toBe(oldPlan.layoutTemplateVersionId);
  expect(before.draftRevision).toBe(workbench.version.draftRevision);
  expect(Array.isArray(before.savePoints)).toBe(true);
  const ordinaryId = oldPlan.edits[0].positionId;
  expect(before.blocks.find((block: { id: string }) => block.id === ordinaryId).text).toBe(oldPlan.edits[0].text);
  expect(before.blocks.filter((block: { id: string }) => block.id === "added:" + draft.additionId)).toHaveLength(1);
  const ordinaryNumber = before.blocks.findIndex((block: { id: string }) => block.id === ordinaryId) + 1;
  await expect(editor.getByRole("textbox", { name: "编辑普通条款" + ordinaryNumber, exact: true })).toHaveValue(oldPlan.edits[0].text);
  const tables = editor.getByRole("region", { name: "合同正文表格", exact: true });
  await expect(tables).toHaveCount(2);
  await expect(tables.nth(0).getByRole("table").getByRole("row").nth(1).getByRole("cell").nth(7)).toHaveText("6.5000");
  await writeFile(testInfo.outputPath("public-before-regeneration.json"), JSON.stringify({ oldPlan, sourceSha256: before.sourceSha256, draftRevision: before.draftRevision, documentContentRevision: before.documentContentRevision, savePoints: before.savePoints }, null, 2));
  const puts: string[] = [];
  page.on("request", request => { if (request.method() === "PUT" && request.url().endsWith("/contract-drafts/" + draft.version.id)) puts.push(request.postData() ?? ""); });
  // First functional RED target: there is currently no full-regeneration entry.
  const regenerate = editor.getByRole("button", { name: "重新生成正文", exact: true });
  await expect(regenerate).toBeVisible();
  await expect(regenerate).toBeEnabled();
  await regenerate.click();
  const dialog = page.getByRole("dialog", { name: "重新生成正文", exact: true });
  await expect(dialog).toBeVisible();
  await expect(dialog).toContainText("手工");
  await expect(dialog).toContainText("新增");
  expect(puts).toHaveLength(0);
  await dialog.getByRole("button", { name: "取消", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect(puts).toHaveLength(0);
  await expect(editor.getByRole("textbox", { name: "编辑普通条款" + ordinaryNumber, exact: true })).toHaveValue(oldPlan.edits[0].text);
  const cancelledResponse = await page.request.get(base + "/document-body", { headers });
  expect(cancelledResponse.status()).toBe(200);
  const cancelled = await cancelledResponse.json();
  expect(cancelled).toEqual(before);
  await regenerate.click();
  await expect(dialog).toBeVisible();
  const savedResponse = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/contract-drafts/" + draft.version.id));
  await dialog.getByRole("button", { name: "确认重新生成", exact: true }).click();
  const saved = await savedResponse;
  const payload = saved.request().postDataJSON();
  await writeFile(testInfo.outputPath("public-regeneration-save-response.json"), JSON.stringify({ status: saved.status(), response: await saved.text(), draftProtocol: payload.draft?.numericProtocolVersion, body: payload.draft?.draftData?.documentBody, action: payload.draft?.draftData?.documentBodyAction }, null, 2));
  expect(payload.draft.numericProtocolVersion).toBe(2);
  expect(payload.draft.draftData.documentBodyAction).toEqual({ kind: "regenerate", confirmOverwrite: true });
  expect(saved.status()).toBe(200);
  const afterResponse = await page.request.get(base + "/document-body", { headers });
  expect(afterResponse.status()).toBe(200);
  const after = await afterResponse.json();
  expect(after.sourceSha256).toBe(before.sourceSha256);
  expect(after.layoutTemplateVersionId).toBe(before.layoutTemplateVersionId);
  expect(after.draftRevision).toBe(before.draftRevision + 1);
  expect(after.documentContentRevision).toBe(before.documentContentRevision + 1);
  expect(after.blocks.find((block: { id: string }) => block.id === ordinaryId).text).toBe(draft.originalOrdinaryText);
  expect(after.blocks.some((block: { id: string }) => block.id.startsWith("added:"))).toBe(false);
  expect(after.savePoints).toHaveLength(before.savePoints.length + 1);
  expect(after.savePoints).toContainEqual(expect.objectContaining({ id: expect.any(String), layoutTemplateVersionId: before.layoutTemplateVersionId, documentContentRevision: before.documentContentRevision, documentBody: oldPlan }));
  const rereadResponse = await page.request.get(base + "/workbench", { headers });
  expect(rereadResponse.status()).toBe(200);
  const reread = await rereadResponse.json();
  expect(reread.version.draftData.documentBodyAction).toBeUndefined();
  const storedPlan = reread.version.draftData.documentBody;
  expect(storedPlan.edits).toEqual([]);
  for (const key of ["additions", "deletedPositionIds", "paragraphOrder"]) expect(storedPlan[key] ?? []).toEqual([]);
  expect(reread.version.amountYuan).toBe("6.5000");
  await page.reload();
  await page.getByText("合同正文", { exact: true }).click();
  const savedOrdinaryNumber = after.blocks.findIndex((block: { id: string }) => block.id === ordinaryId) + 1;
  await expect(editor.getByRole("textbox", { name: "编辑普通条款" + savedOrdinaryNumber, exact: true })).toHaveValue(draft.originalOrdinaryText);
  await expect(editor.getByText("重新生成前已保存的新增约定。", { exact: false })).toHaveCount(0);
  const reloadedTables = editor.getByRole("region", { name: "合同正文表格", exact: true });
  await expect(reloadedTables).toHaveCount(2);
  const amountCell = reloadedTables.nth(0).getByRole("table").getByRole("row").nth(1).getByRole("cell").nth(7);
  await expect(amountCell).toHaveText("6.5000");
  await expect(amountCell.getByRole("textbox")).toHaveCount(0);
  const dimensions = await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth }));
  expect(dimensions.documentWidth).toBeLessThanOrEqual(dimensions.viewport + 1);
  await page.screenshot({ path: testInfo.outputPath("regenerated-body.png"), fullPage: true });
  await writeFile(testInfo.outputPath("receipt.json"), JSON.stringify({ sourceSha256: after.sourceSha256, draftRevision: after.draftRevision, documentContentRevision: after.documentContentRevision, savedPriorPlan: oldPlan, savePoints: after.savePoints, dimensions, scope: "same-template explicit regeneration/cancel/confirmed aggregate save/original manual checkpoint; not template change, A4 or DOCX/PDF export" }, null, 2));
});
