import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { expect, test } from "@playwright/test";

test("删除保存回执消费窄意图后可再次保存非正文合同名称", async ({ page }, testInfo) => {
  const input = JSON.parse(process.env.TASK10_BODY_BROWSER_INPUT ?? "{}");
  const draft = input.drafts[testInfo.project.name];
  const target = "/合同工作台/" + draft.contract.id + "?versionId=" + draft.version.id;
  await page.goto("/login?redirect=" + encodeURIComponent(target));
  await page.getByPlaceholder("请输入手机号").fill(input.staff.phone);
  await page.getByPlaceholder("请输入密码").fill(input.staff.password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.getByText("合同正文", { exact: true }).click();
  const editor = page.getByRole("region", { name: "完整合同正文", exact: true });
  await expect(editor).toBeVisible();
  const sources = [];
  for (const file of ["src/pages/contracts/ContractWorkbenchPage.vue", "src/pages/contracts/workbench/ContractBodyEditor.vue", "src/pages/contracts/workbench/ContractBodyFlow.vue", "src/pages/contracts/workbench/use-contract-draft.ts"]) {
    const response = await page.request.get("/" + file);
    expect(response.status()).toBe(200);
    const bytes = await response.body();
    await writeFile(testInfo.outputPath(file.split("/").at(-1)! + ".served.js"), bytes);
    sources.push({ file, diskSha256: createHash("sha256").update(await readFile(resolve(file))).digest("hex"), publicServedJavaScriptSha256: createHash("sha256").update(bytes).digest("hex") });
  }
  await writeFile(testInfo.outputPath("public-source-freshness.json"), JSON.stringify(sources, null, 2));
  const login = await page.request.post("/api/auth/login", { data: input.staff });
  expect(login.status()).toBe(201);
  const headers = { authorization: "Bearer " + (await login.json()).tokens.accessToken, "x-contract-numeric-protocol": "2" };
  const workbenchResponse = await page.request.get("/api/contract-drafts/" + draft.version.id + "/workbench", { headers });
  expect(workbenchResponse.status()).toBe(200);
  const workbench = await workbenchResponse.json();
  const nameDefinition = workbench.businessEntry?.definition?.fields?.find((field: { key: string }) => field.key === "contractName");
  expect(nameDefinition?.label).toBe("合同名称");
  const originalPlan = workbench.version.draftData.documentBody;
  expect(originalPlan.edits).toEqual([]);
  expect(originalPlan.additions).toEqual([{ id: draft.additionId, afterPositionId: expect.any(String), text: "唯一新增手工条款：本次明确删除本段。" }]);
  expect(originalPlan.deletedPositionIds ?? []).toEqual([]);
  expect(originalPlan.paragraphOrder ?? []).toEqual([]);
  expect(workbench.version.draftData.documentBodyAction).toBeUndefined();
  const response = await page.request.get("/api/contract-drafts/" + draft.version.id + "/document-body", { headers });
  expect(response.status()).toBe(200);
  const before = await response.json();
  expect(before.sourceSha256).toBe(input.sourceSha256);
  expect(before.draftRevision).toBe(workbench.version.draftRevision);
  expect(originalPlan.layoutTemplateVersionId).toBe(before.layoutTemplateVersionId);
  expect(originalPlan.sourceSha256).toBe(before.sourceSha256);
  const ordinary = before.blocks.find((block: { editable: boolean; text: string }) => block.editable && block.text.includes("4.若卖方违背"));
  expect(ordinary).toBeDefined();
  expect(ordinary.text).toBe(draft.originalOrdinaryText);
  expect(ordinary.text).not.toContain("原有人工条款需保留。");
  expect(originalPlan.additions[0].afterPositionId).toBe(ordinary.id);
  expect(before.blocks.filter((block: { id: string }) => block.id.startsWith("added:"))).toHaveLength(1);
  const added = before.blocks.filter((block: { id: string }) => block.id === "added:" + draft.additionId);
  expect(added).toHaveLength(1);
  expect(added[0]).toMatchObject({ editable: true, text: "补充条款1：唯一新增手工条款：本次明确删除本段。" });
  const ordinaryNumber = before.blocks.findIndex((block: { id: string }) => block.id === ordinary.id) + 1;
  const addedNumber = before.blocks.findIndex((block: { id: string }) => block.id === added[0].id) + 1;
  const ordinaryText = editor.getByRole("textbox", { name: "编辑普通条款" + ordinaryNumber, exact: true });
  const addedText = editor.getByRole("textbox", { name: "编辑普通条款" + addedNumber, exact: true });
  await expect(ordinaryText).toHaveValue(ordinary.text);
  await expect(addedText).toHaveValue(added[0].text);
  await expect(addedText).toBeEditable();
  await expect(editor.getByRole("button", { name: "保存正文", exact: true })).toBeEnabled();
  const tables = editor.getByRole("region", { name: "合同正文表格", exact: true });
  await expect(tables).toHaveCount(2);
  await expect(tables.nth(0).getByRole("table").getByRole("row").nth(1).getByRole("cell").nth(7)).toHaveText("6.5000");
  await writeFile(testInfo.outputPath("public-before-deletion.json"), JSON.stringify({ sourceSha256: before.sourceSha256, documentContentRevision: before.documentContentRevision, draftRevision: before.draftRevision, originalPlan, ordinary, added: added[0], scope: "exactly one persisted manual addition/no other manual plans; real public delete/save response should200, current whole-manual-reset guard predicts409" }, null, 2));
  const addedParagraph = editor.locator(".body-paragraph").filter({ has: page.getByRole("textbox", { name: "编辑普通条款" + addedNumber, exact: true }) });
  await expect(addedParagraph).toHaveCount(1);
  const deletion = addedParagraph.getByRole("button", { name: "删除新增条款", exact: true });
  await expect(deletion).toBeVisible();
  await expect(deletion).toBeEnabled();
  const savedResponse = page.waitForResponse(value => {
    if (value.request().method() !== "PUT" || !value.url().endsWith("/contract-drafts/" + draft.version.id)) return false;
    const plan = value.request().postDataJSON()?.draft?.draftData?.documentBody;
    return Boolean(plan && !plan.additions?.some((item: { id: string }) => item.id === draft.additionId) &&
      Array.isArray(plan.edits) && plan.edits.length === 0);
  });
  await deletion.click();
  await editor.getByRole("button", { name: "保存正文", exact: true }).click();
  const savedResponseValue = await savedResponse;
  const savedPayload = savedResponseValue.request().postDataJSON();
  const firstResponseText = await savedResponseValue.text();
  await writeFile(testInfo.outputPath("public-first-deletion-save-response.json"), JSON.stringify({ status: savedResponseValue.status(), response: firstResponseText, idempotencyKey: savedPayload.idempotencyKey, expectedRevision: savedPayload.expectedRevision, draftNumericProtocolVersion: savedPayload.draft?.numericProtocolVersion, documentBody: savedPayload.draft?.draftData?.documentBody, documentBodyAction: savedPayload.draft?.draftData?.documentBodyAction ?? null }, null, 2));
  expect(savedPayload.draft.numericProtocolVersion).toBe(2);
  expect(savedPayload.draft.draftData.documentBodyAction).toEqual({ kind: "delete_saved_addition", additionId: draft.additionId });
  expect(savedResponseValue.status()).toBe(200);
  const firstReceipt = JSON.parse(firstResponseText);
  const reread = await page.request.get("/api/contract-drafts/" + draft.version.id + "/document-body", { headers });
  expect(reread.status()).toBe(200);
  const saved = await reread.json();
  expect(saved.sourceSha256).toBe(input.sourceSha256);
  expect(saved.layoutTemplateVersionId).toBe(before.layoutTemplateVersionId);
  expect(saved.blocks.some((block: { id: string }) => block.id === added[0].id)).toBe(false);
  expect(saved.blocks.some((block: { text: string }) => block.text.includes("唯一新增手工条款"))).toBe(false);
  expect(saved.blocks.find((block: { id: string }) => block.id === ordinary.id).text).toBe(ordinary.text);
  // No reload or body edit may clear the instruction before this second PUT.
  // The existing filling UI changes only a non-body field through applyPatch.
  await page.getByText("填写信息", { exact: true }).click();
  await page.getByRole("navigation", { name: "合同资料章节", exact: true }).getByRole("link", { name: "基础信息", exact: true }).click();
  const basic = page.locator('section[data-section-id="basic"]');
  const contractName = basic.getByRole("textbox", { name: /合同名称/u });
  await expect(contractName).toHaveCount(1);
  await expect(contractName).toBeEditable();
  await expect(contractName).toHaveValue("上游新建当前合同名称");
  const changedName = "任务10删除回执后更新名称";
  const secondSavedResponse = page.waitForResponse(value => value.request().method() === "PUT" && value.url().endsWith("/contract-drafts/" + draft.version.id) &&
    value.request().postDataJSON()?.draft?.draftData?.contractName === changedName);
  await contractName.fill(changedName);
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  const secondResponse = await secondSavedResponse;
  const secondPayload = secondResponse.request().postDataJSON();
  const secondResponseText = await secondResponse.text();
  await writeFile(testInfo.outputPath("public-nonbody-save-response.json"), JSON.stringify({ status: secondResponse.status(), response: secondResponseText, idempotencyKey: secondPayload.idempotencyKey, expectedRevision: secondPayload.expectedRevision, draftNumericProtocolVersion: secondPayload.draft?.numericProtocolVersion, contractName: secondPayload.draft?.draftData?.contractName, documentBody: secondPayload.draft?.draftData?.documentBody, hasDocumentBodyAction: Object.hasOwn(secondPayload.draft?.draftData ?? {}, "documentBodyAction"), documentBodyAction: secondPayload.draft?.draftData?.documentBodyAction ?? null }, null, 2));
  expect(secondPayload.idempotencyKey).not.toBe(savedPayload.idempotencyKey);
  expect(secondPayload.expectedRevision).toBe(firstReceipt.serverRevision);
  expect(secondPayload.draft.numericProtocolVersion).toBe(2);
  expect(Object.hasOwn(secondPayload.draft.draftData, "documentBodyAction")).toBe(false);
  expect(secondResponse.status()).toBe(200);
  const secondReceipt = JSON.parse(secondResponseText);
  expect(secondReceipt.serverRevision).toBe(firstReceipt.serverRevision + 1);
  const afterWorkbenchResponse = await page.request.get("/api/contract-drafts/" + draft.version.id + "/workbench", { headers });
  expect(afterWorkbenchResponse.status()).toBe(200);
  const afterWorkbench = await afterWorkbenchResponse.json();
  expect(afterWorkbench.version.draftRevision).toBe(secondReceipt.serverRevision);
  expect(afterWorkbench.version.draftData.contractName).toBe(changedName);
  expect(afterWorkbench.version.draftData.documentBodyAction).toBeUndefined();
  expect(afterWorkbench.version.amountYuan).toBe("6.5000");
  const afterBodyResponse = await page.request.get("/api/contract-drafts/" + draft.version.id + "/document-body", { headers });
  expect(afterBodyResponse.status()).toBe(200);
  const afterNonBody = await afterBodyResponse.json();
  expect(afterNonBody.draftRevision).toBe(secondReceipt.serverRevision);
  expect(afterNonBody.sourceSha256).toBe(input.sourceSha256);
  expect(afterNonBody.layoutTemplateVersionId).toBe(before.layoutTemplateVersionId);
  expect(afterNonBody.blocks.some((block: { id: string }) => block.id.startsWith("added:"))).toBe(false);
  expect(afterNonBody.blocks.find((block: { id: string }) => block.id === ordinary.id).text).toBe(ordinary.text);
  const storedPlan = afterWorkbench.version.draftData.documentBody;
  expect(storedPlan.edits).toEqual([]);
  for (const key of ["additions", "deletedPositionIds", "paragraphOrder"]) expect(storedPlan[key] ?? []).toEqual([]);
  await page.reload();
  await page.getByText("合同正文", { exact: true }).click();
  await expect(editor.getByText("唯一新增手工条款", { exact: false })).toHaveCount(0);
  const savedOrdinaryNumber = saved.blocks.findIndex((block: { id: string }) => block.id === ordinary.id) + 1;
  await expect(editor.getByRole("textbox", { name: "编辑普通条款" + savedOrdinaryNumber, exact: true })).toHaveValue(ordinary.text);
  const reloadedTables = editor.getByRole("region", { name: "合同正文表格", exact: true });
  await expect(reloadedTables).toHaveCount(2);
  const amountCell = reloadedTables.nth(0).getByRole("table").getByRole("row").nth(1).getByRole("cell").nth(7);
  await expect(amountCell).toHaveText("6.5000");
  await expect(amountCell.getByRole("textbox")).toHaveCount(0);
  const dimensions = await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth }));
  expect(dimensions.documentWidth).toBeLessThanOrEqual(dimensions.viewport + 1);
  await page.getByText("填写信息", { exact: true }).click();
  await page.getByRole("navigation", { name: "合同资料章节", exact: true }).getByRole("link", { name: "基础信息", exact: true }).click();
  await expect(basic.getByRole("textbox", { name: /合同名称/u })).toHaveValue(changedName);
  await page.screenshot({ path: testInfo.outputPath("ack-consumed-followup-name.png"), fullPage: true });
  await writeFile(testInfo.outputPath("receipt.json"), JSON.stringify({ sourceSha256: saved.sourceSha256, documentContentRevision: afterNonBody.documentContentRevision, removedAdditionId: added[0].id, retainedOrdinary: ordinary.text, changedName, firstSaveRevision: firstReceipt.serverRevision, secondSaveRevision: secondReceipt.serverRevision, firstKey: savedPayload.idempotencyKey, secondKey: secondPayload.idempotencyKey, secondHadAction: Object.hasOwn(secondPayload.draft.draftData, "documentBodyAction"), dimensions, scope: "normal ACK consumption proved by a real non-body name edit/secondPUT200 without action before reload; not query/lost-response ACK or arbitrary mixed commands" }, null, 2));
});
