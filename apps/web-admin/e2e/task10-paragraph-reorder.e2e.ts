import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { expect, test } from "@playwright/test";

test("同组普通条款上移一位并保留手改和其他全部正文位置", async ({ page }, testInfo) => {
  const input = JSON.parse(process.env.TASK10_BODY_BROWSER_INPUT ?? "{}");
  const draft = input.drafts.desktop;
  const target = "/合同工作台/" + draft.contract.id + "?versionId=" + draft.version.id;
  await page.goto("/login?redirect=" + encodeURIComponent(target));
  await page.getByPlaceholder("请输入手机号").fill(input.staff.phone);
  await page.getByPlaceholder("请输入密码").fill(input.staff.password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.getByText("合同正文", { exact: true }).click();
  const editor = page.getByRole("region", { name: "完整合同正文", exact: true });
  await expect(editor).toBeVisible();
  await expect(editor.getByRole("button", { name: "保存正文", exact: true })).toBeEnabled();
  const freshness = [];
  for (const file of ["src/pages/contracts/ContractWorkbenchPage.vue", "src/pages/contracts/workbench/ContractBodyEditor.vue", "src/pages/contracts/workbench/ContractBodyFlow.vue", "src/pages/contracts/workbench/use-contract-draft.ts"]) {
    const response = await page.request.get("/" + file);
    expect(response.status()).toBe(200);
    const bytes = await response.body();
    await writeFile(testInfo.outputPath(file.split("/").at(-1)! + ".served.js"), bytes);
    freshness.push({ file, diskSha256: createHash("sha256").update(await readFile(resolve(file))).digest("hex"), publicServedJavaScriptSha256: createHash("sha256").update(bytes).digest("hex") });
  }
  await writeFile(testInfo.outputPath("public-source-freshness.json"), JSON.stringify(freshness, null, 2));
  const login = await page.request.post("/api/auth/login", { data: input.staff });
  expect(login.status()).toBe(201);
  const headers = { authorization: "Bearer " + (await login.json()).tokens.accessToken, "x-contract-numeric-protocol": "2" };
  const base = "/api/contract-drafts/" + draft.version.id;
  const workbenchResponse = await page.request.get(base + "/workbench", { headers });
  expect(workbenchResponse.status()).toBe(200);
  const workbench = await workbenchResponse.json();
  const originalPlan = workbench.version.draftData.documentBody;
  expect(originalPlan.edits).toEqual([{ positionId: draft.paragraphA, text: draft.manualA }]);
  for (const key of ["additions", "deletedPositionIds", "paragraphOrder"]) expect(originalPlan[key] ?? []).toEqual([]);
  expect(workbench.version.numericProtocolVersion).toBe(2);
  expect(workbench.version.amountYuan).toBe("6.5000");
  const response = await page.request.get(base + "/document-body", { headers });
  expect(response.status()).toBe(200);
  const before = await response.json();
  expect(before.sourceSha256).toBe(input.sourceSha256);
  expect(before.sourceSha256).toBe(originalPlan.sourceSha256);
  expect(before.layoutTemplateVersionId).toBe(originalPlan.layoutTemplateVersionId);
  expect(before.draftRevision).toBe(workbench.version.draftRevision);
  const a = before.blocks.find((block: { id: string }) => block.id === draft.paragraphA);
  const b = before.blocks.find((block: { id: string }) => block.id === draft.paragraphB);
  expect(a).toMatchObject({ kind: "paragraph", editable: true, text: draft.manualA });
  expect(b).toMatchObject({ kind: "paragraph", editable: true, text: draft.originalB });
  const groupIndex = before.paragraphGroups.findIndex((group: string[]) => group.includes(a.id));
  expect(groupIndex).toBeGreaterThanOrEqual(0);
  const group = before.paragraphGroups[groupIndex];
  expect(group).toEqual(["ff018d5aaa492b1a0055fcb9d50d23e85aa52b562a7f8cf940d7cb0f59683d0c", a.id, b.id, "7551ee090ac74d72775135f4316553b4d0a353c2dccfd369ef996be28bcbf85d"]);
  const aFlowIndex = before.flow.findIndex((item: { kind: string; paragraphId?: string }) => item.kind === "paragraph" && item.paragraphId === a.id);
  const bFlowIndex = before.flow.findIndex((item: { kind: string; paragraphId?: string }) => item.kind === "paragraph" && item.paragraphId === b.id);
  expect(aFlowIndex).toBeGreaterThanOrEqual(0);
  expect(bFlowIndex).toBe(aFlowIndex + 1);
  const aNumber = before.blocks.findIndex((block: { id: string }) => block.id === a.id) + 1;
  const bNumber = before.blocks.findIndex((block: { id: string }) => block.id === b.id) + 1;
  await expect(editor.getByRole("textbox", { name: "编辑普通条款" + aNumber, exact: true })).toHaveValue(draft.manualA);
  await expect(editor.getByRole("textbox", { name: "编辑普通条款" + bNumber, exact: true })).toHaveValue(draft.originalB);
  const tables = editor.getByRole("region", { name: "合同正文表格", exact: true });
  await expect(tables).toHaveCount(2);
  const originalAmount = tables.nth(0).getByRole("table").getByRole("row").nth(1).getByRole("cell").nth(7);
  await expect(originalAmount).toHaveText("6.5000");
  await expect(originalAmount.getByRole("textbox")).toHaveCount(0);
  const expectedGroups: string[][] = before.paragraphGroups.map((items: string[], index: number) => index === groupIndex ? [group[0], b.id, a.id, group[3]] : [...items]);
  const expectedFlow = [...before.flow];
  [expectedFlow[aFlowIndex], expectedFlow[bFlowIndex]] = [expectedFlow[bFlowIndex], expectedFlow[aFlowIndex]];
  await writeFile(testInfo.outputPath("public-before-reorder.json"), JSON.stringify({ originalPlan, sourceSha256: before.sourceSha256, layoutTemplateVersionId: before.layoutTemplateVersionId, draftRevision: before.draftRevision, documentContentRevision: before.documentContentRevision, groups: before.paragraphGroups, flow: before.flow, expectedGroups, expectedFlow }, null, 2));
  const bParagraph = editor.locator(".body-paragraph").filter({ has: page.getByRole("textbox", { name: "编辑普通条款" + bNumber, exact: true }) });
  await expect(bParagraph).toHaveCount(1);
  const move = bParagraph.getByRole("button", { name: "上移条款", exact: true });
  // First functional RED target after fresh public source/group/edit/DOM checks.
  await expect(move).toBeVisible();
  await expect(move).toBeEnabled();
  const savedResponse = page.waitForResponse(value => value.request().method() === "PUT" && value.url().endsWith("/contract-drafts/" + draft.version.id));
  await move.click();
  await editor.getByRole("button", { name: "保存正文", exact: true }).click();
  const saved = await savedResponse;
  const payload = saved.request().postDataJSON();
  await writeFile(testInfo.outputPath("public-reorder-save-response.json"), JSON.stringify({ status: saved.status(), response: await saved.text(), plan: payload.draft?.draftData?.documentBody }, null, 2));
  expect(payload.draft.draftData.documentBody.paragraphOrder).toEqual(expectedGroups.flat());
  expect(payload.draft.draftData.documentBody.edits).toEqual(originalPlan.edits);
  expect(saved.status()).toBe(200);
  const afterResponse = await page.request.get(base + "/document-body", { headers });
  expect(afterResponse.status()).toBe(200);
  const after = await afterResponse.json();
  expect(after.sourceSha256).toBe(before.sourceSha256);
  expect(after.layoutTemplateVersionId).toBe(before.layoutTemplateVersionId);
  expect(after.draftRevision).toBe(before.draftRevision + 1);
  expect(after.documentContentRevision).toBe(before.documentContentRevision + 1);
  expect(after.paragraphGroups).toEqual(expectedGroups);
  expect(after.flow).toEqual(expectedFlow);
  expect(after.blocks.find((block: { id: string }) => block.id === a.id).text).toBe(draft.manualA);
  expect(after.blocks.find((block: { id: string }) => block.id === b.id).text).toBe(draft.originalB);
  // All other logical blocks, including complete tables and hidden group IDs,
  // remain represented; only the selected two source paragraphs change order.
  expect(after.blocks.filter((block: { id: string }) => ![a.id, b.id].includes(block.id))).toEqual(before.blocks.filter((block: { id: string }) => ![a.id, b.id].includes(block.id)));
  await page.reload();
  await page.getByText("合同正文", { exact: true }).click();
  const afterANumber = after.blocks.findIndex((block: { id: string }) => block.id === a.id) + 1;
  const afterBNumber = after.blocks.findIndex((block: { id: string }) => block.id === b.id) + 1;
  await expect(editor.getByRole("textbox", { name: "编辑普通条款" + afterANumber, exact: true })).toHaveValue(draft.manualA);
  await expect(editor.getByRole("textbox", { name: "编辑普通条款" + afterBNumber, exact: true })).toHaveValue(draft.originalB);
  const aDOMIndex = await editor.getByRole("textbox", { name: "编辑普通条款" + afterANumber, exact: true }).evaluate(element => Array.from(element.ownerDocument.querySelectorAll("textarea")).indexOf(element as HTMLTextAreaElement));
  const bDOMIndex = await editor.getByRole("textbox", { name: "编辑普通条款" + afterBNumber, exact: true }).evaluate(element => Array.from(element.ownerDocument.querySelectorAll("textarea")).indexOf(element as HTMLTextAreaElement));
  expect(bDOMIndex).toBeGreaterThanOrEqual(0);
  expect(aDOMIndex).toBeGreaterThan(bDOMIndex);
  const reloadedTables = editor.getByRole("region", { name: "合同正文表格", exact: true });
  await expect(reloadedTables).toHaveCount(2);
  const amount = reloadedTables.nth(0).getByRole("table").getByRole("row").nth(1).getByRole("cell").nth(7);
  await expect(amount).toHaveText("6.5000");
  await expect(amount.getByRole("textbox")).toHaveCount(0);
  const dimensions = await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth }));
  expect(dimensions.documentWidth).toBeLessThanOrEqual(dimensions.viewport + 1);
  await page.screenshot({ path: testInfo.outputPath("paragraph-reordered.png"), fullPage: true });
  await writeFile(testInfo.outputPath("receipt.json"), JSON.stringify({ sourceSha256: after.sourceSha256, groups: after.paragraphGroups, flow: after.flow, manualA: draft.manualA, dimensions, scope: "desktop same-group adjacent sourceB aboveA, preserve allothergroups/hiddenIDs/manualA/tables/6.5000; not mobile/crossgroup/addedorder/DOCXPDF" }, null, 2));
});
