import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { expect, test } from "@playwright/test";

test("删除已保存新增条款后保留其他人工正文", async ({ page }, testInfo) => {
  const input = JSON.parse(process.env.TASK10_BODY_BROWSER_INPUT ?? "{}");
  const draft = input.drafts[testInfo.project.name];
  const target = "/合同工作台/" + draft.contract.id + "?versionId=" + draft.version.id;
  await page.goto("/login?redirect=" + encodeURIComponent(target));
  await page.getByPlaceholder("请输入手机号").fill(input.staff.phone);
  await page.getByPlaceholder("请输入密码").fill(input.staff.password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.getByText("合同正文", { exact: true }).click();
  const editor = page.getByRole("region", { name: "完整合同正文", exact: true });
  await expect(editor).toBeVisible();
  const sources = [];
  for (const file of ["src/pages/contracts/ContractWorkbenchPage.vue", "src/pages/contracts/workbench/ContractBodyEditor.vue", "src/pages/contracts/workbench/ContractBodyFlow.vue"]) {
    const response = await page.request.get("/" + file);
    expect(response.status()).toBe(200);
    const bytes = await response.body();
    await writeFile(testInfo.outputPath(file.split("/").at(-1)! + ".served.js"), bytes);
    sources.push({ file, diskSha256: createHash("sha256").update(await readFile(resolve(file))).digest("hex"), publicServedJavaScriptSha256: createHash("sha256").update(bytes).digest("hex") });
  }
  await writeFile(testInfo.outputPath("public-source-freshness.json"), JSON.stringify(sources, null, 2));
  const login = await page.request.post("/api/auth/login", { data: input.staff });
  expect(login.status()).toBe(201);
  const headers = { authorization: "Bearer " + (await login.json()).tokens.accessToken, "x-contract-numeric-protocol": "2" };
  const response = await page.request.get("/api/contract-drafts/" + draft.version.id + "/document-body", { headers });
  expect(response.status()).toBe(200);
  const before = await response.json();
  expect(before.sourceSha256).toBe(input.sourceSha256);
  const ordinary = before.blocks.find((block: { editable: boolean; text: string }) => block.editable && block.text.includes("4.若卖方违背"));
  expect(ordinary).toBeDefined();
  expect(ordinary.text).toContain("原有人工条款需保留。");
  const added = before.blocks.filter((block: { id: string }) => block.id === "added:" + draft.additionId);
  expect(added).toHaveLength(1);
  expect(added[0]).toMatchObject({ editable: true, text: "补充条款1：待删除新增条款：检验后不再保留本段。" });
  const ordinaryNumber = before.blocks.findIndex((block: { id: string }) => block.id === ordinary.id) + 1;
  const addedNumber = before.blocks.findIndex((block: { id: string }) => block.id === added[0].id) + 1;
  const ordinaryText = editor.getByRole("textbox", { name: "编辑普通条款" + ordinaryNumber, exact: true });
  const addedText = editor.getByRole("textbox", { name: "编辑普通条款" + addedNumber, exact: true });
  await expect(ordinaryText).toHaveValue(ordinary.text);
  await expect(addedText).toHaveValue(added[0].text);
  await expect(addedText).toBeEditable();
  await expect(editor.getByRole("button", { name: "保存正文", exact: true })).toBeEnabled();
  const tables = editor.getByRole("region", { name: "合同正文表格", exact: true });
  await expect(tables).toHaveCount(2);
  await expect(tables.nth(0).getByRole("table").getByRole("row").nth(1).getByRole("cell").nth(7)).toHaveText("6.5000");
  await writeFile(testInfo.outputPath("public-before-deletion.json"), JSON.stringify({ sourceSha256: before.sourceSha256, documentContentRevision: before.documentContentRevision, ordinary, added: added[0], scope: "real formal source/full application/public HTTP; deletion entry is the first predicted behavioral RED" }, null, 2));
  const addedParagraph = editor.locator(".body-paragraph").filter({ has: page.getByRole("textbox", { name: "编辑普通条款" + addedNumber, exact: true }) });
  await expect(addedParagraph).toHaveCount(1);
  const deletion = addedParagraph.getByRole("button", { name: "删除新增条款", exact: true });
  await expect(deletion).toBeVisible();
  await expect(deletion).toBeEnabled();
  const savedResponse = page.waitForResponse(value => {
    if (value.request().method() !== "PUT" || !value.url().endsWith("/contract-drafts/" + draft.version.id)) return false;
    const plan = value.request().postDataJSON()?.draft?.draftData?.documentBody;
    return Boolean(plan && !plan.additions?.some((item: { id: string }) => item.id === draft.additionId) &&
      plan.edits?.some((item: { positionId: string; text: string }) => item.positionId === ordinary.id && item.text === ordinary.text));
  });
  await deletion.click();
  await editor.getByRole("button", { name: "保存正文", exact: true }).click();
  expect((await savedResponse).status()).toBe(200);
  const reread = await page.request.get("/api/contract-drafts/" + draft.version.id + "/document-body", { headers });
  expect(reread.status()).toBe(200);
  const saved = await reread.json();
  expect(saved.sourceSha256).toBe(input.sourceSha256);
  expect(saved.layoutTemplateVersionId).toBe(before.layoutTemplateVersionId);
  expect(saved.blocks.some((block: { id: string }) => block.id === added[0].id)).toBe(false);
  expect(saved.blocks.some((block: { text: string }) => block.text.includes("待删除新增条款"))).toBe(false);
  expect(saved.blocks.find((block: { id: string }) => block.id === ordinary.id).text).toBe(ordinary.text);
  await page.reload();
  await page.getByText("合同正文", { exact: true }).click();
  await expect(editor.getByText("待删除新增条款", { exact: false })).toHaveCount(0);
  const savedOrdinaryNumber = saved.blocks.findIndex((block: { id: string }) => block.id === ordinary.id) + 1;
  await expect(editor.getByRole("textbox", { name: "编辑普通条款" + savedOrdinaryNumber, exact: true })).toHaveValue(ordinary.text);
  const reloadedTables = editor.getByRole("region", { name: "合同正文表格", exact: true });
  await expect(reloadedTables).toHaveCount(2);
  const amountCell = reloadedTables.nth(0).getByRole("table").getByRole("row").nth(1).getByRole("cell").nth(7);
  await expect(amountCell).toHaveText("6.5000");
  await expect(amountCell.getByRole("textbox")).toHaveCount(0);
  const dimensions = await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth }));
  expect(dimensions.documentWidth).toBeLessThanOrEqual(dimensions.viewport + 1);
  await page.screenshot({ path: testInfo.outputPath("deleted-addition.png"), fullPage: true });
  await writeFile(testInfo.outputPath("receipt.json"), JSON.stringify({ sourceSha256: saved.sourceSha256, documentContentRevision: saved.documentContentRevision, removedAdditionId: added[0].id, retainedOrdinary: ordinary.text, dimensions, scope: "delete one saved addition with another manual edit retained; not deletion of the only manual content, regeneration, ordering or export" }, null, 2));
});

test("删除原有普通条款后保存重读并保留其他内容", async ({ page }, testInfo) => {
  const input = JSON.parse(process.env.TASK10_BODY_BROWSER_INPUT ?? "{}"), draft = input.drafts[testInfo.project.name];
  await page.goto("/login?redirect=" + encodeURIComponent("/合同工作台/" + draft.contract.id + "?versionId=" + draft.version.id));
  await page.getByPlaceholder("请输入手机号").fill(input.staff.phone); await page.getByPlaceholder("请输入密码").fill(input.staff.password); await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.getByText("合同正文", { exact: true }).click();
  const editor = page.getByRole("region", { name: "完整合同正文", exact: true }); await expect(editor).toBeVisible();
  const sourceProof = [];
  for (const file of ["src/pages/contracts/workbench/ContractBodyEditor.vue", "src/pages/contracts/workbench/ContractBodyFlow.vue"]) {
    const response = await page.request.get("/" + file); expect(response.status()).toBe(200); const bytes = await response.body();
    await writeFile(testInfo.outputPath(file.split("/").at(-1)! + ".served.js"), bytes); sourceProof.push({ file, diskSha256: createHash("sha256").update(await readFile(resolve(file))).digest("hex"), servedSha256: createHash("sha256").update(bytes).digest("hex") });
  }
  const login = await page.request.post("/api/auth/login", { data: input.staff }); expect(login.status()).toBe(201);
  const headers = { authorization: "Bearer " + (await login.json()).tokens.accessToken, "x-contract-numeric-protocol": "2" };
  const get = async (suffix: string) => { const response = await page.request.get("/api/contract-drafts/" + draft.version.id + suffix, { headers }); expect(response.status()).toBe(200); return response.json(); };
  const before = await get("/document-body"), facts = await get("/workbench");
  expect(before.sourceSha256).toBe(input.sourceSha256); expect(facts.version.amountYuan).toBe("6.5000");
  const target = before.blocks.find((block: { id: string }) => block.id === draft.targetId), retained = before.blocks.find((block: { id: string }) => block.id === draft.retainedId);
  expect(target.editable).toBe(true); expect(target.id.startsWith("added:")).toBe(false); expect(target.text).toContain("原段删除目标文字。"); expect(retained.text).toContain("其他人工正文必须保留。");
  const number = before.blocks.findIndex((block: { id: string }) => block.id === target.id) + 1;
  const textbox = editor.getByRole("textbox", { name: "编辑普通条款" + number, exact: true }); await expect(textbox).toHaveValue(target.text);
  const targetParagraph = editor.locator(".body-paragraph").filter({ has: page.getByRole("textbox", { name: "编辑普通条款" + number, exact: true }) }); await expect(targetParagraph).toHaveCount(1);
  const protectedBlocks = before.blocks.filter((block: { editable: boolean }) => !block.editable);
  expect(protectedBlocks.length).toBeGreaterThan(0);
  const tables = editor.getByRole("region", { name: "合同正文表格", exact: true }); await expect(tables).toHaveCount(2);
  await expect(tables.nth(0).getByRole("table").getByRole("row").nth(1).getByRole("cell").nth(7)).toHaveText("6.5000");
  await writeFile(testInfo.outputPath("public-original-deletion-before.json"), JSON.stringify({ before, facts, target, retained, sourceProof, firstExpectedBehavior: "source ordinary paragraph must offer a real delete entry, not only added paragraphs" }, null, 2));
  const retainedNumberBefore = before.blocks.findIndex((block: { id: string }) => block.id === retained.id) + 1;
  const anchor = editor.locator(".body-paragraph").filter({ has: page.getByRole("textbox", { name: "编辑普通条款" + retainedNumberBefore, exact: true }) });
  await expect(anchor.getByRole("button", { name: "删除普通条款", exact: true })).toBeDisabled();
  await expect(anchor.getByRole("note").filter({ hasText: "此条款后有新增条款，请先处理新增条款，再删除原条款。" })).toBeVisible();
  const remove = targetParagraph.getByRole("button", { name: "删除普通条款", exact: true }); await expect(remove).toBeVisible(); await expect(remove).toBeEnabled();
  const acknowledged = page.waitForResponse(response => {
    if (response.request().method() !== "PUT" || !response.url().endsWith("/contract-drafts/" + draft.version.id)) return false;
    const plan = response.request().postDataJSON()?.draft?.draftData?.documentBody;
    return Boolean(plan?.deletedPositionIds?.includes(target.id) && !plan.edits.some((edit: { positionId: string }) => edit.positionId === target.id));
  });
  await remove.click(); await expect(targetParagraph).toHaveCount(0); await editor.getByRole("button", { name: "保存正文", exact: true }).click(); expect((await acknowledged).status()).toBe(200);
  const after = await get("/document-body"), saved = await get("/workbench");
  expect(after.sourceSha256).toBe(before.sourceSha256); expect(after.layoutTemplateVersionId).toBe(before.layoutTemplateVersionId);
  expect(after.blocks).toEqual(before.blocks.filter((block: { id: string }) => block.id !== target.id).map((block: { id: string }, index: number) => block.id.startsWith("generated:") ? { ...block, id: `generated:${index}` } : block));
  expect(after.blocks.some((block: { text: string }) => block.text.includes("原段删除目标文字。"))).toBe(false);
  const plan = saved.version.draftData.documentBody, oldPlan = facts.version.draftData.documentBody;
  expect(plan.deletedPositionIds).toEqual([target.id]); expect(plan.edits).toEqual(oldPlan.edits.filter((edit: { positionId: string }) => edit.positionId !== target.id));
  expect(plan.additions).toEqual(oldPlan.additions); expect(plan.paragraphOrder).toEqual(oldPlan.paragraphOrder.filter((id: string) => id !== target.id));
  expect(saved.version.amountYuan).toBe(facts.version.amountYuan); expect(saved.bills).toEqual(facts.bills);
  expect(saved.version.documentContentRevision).toBeGreaterThan(facts.version.documentContentRevision); expect(saved.version.documentContentFingerprint).not.toBe(facts.version.documentContentFingerprint);
  expect(after.documentContentRevision).toBe(saved.version.documentContentRevision);
  await page.reload(); await page.getByText("合同正文", { exact: true }).click();
  const reloaded = await get("/document-body"), reloadedFacts = await get("/workbench"); expect(reloaded).toEqual(after); expect(reloadedFacts.version).toEqual(saved.version);
  const retainedNumber = reloaded.blocks.findIndex((block: { id: string }) => block.id === retained.id) + 1;
  await expect(editor.getByRole("textbox", { name: "编辑普通条款" + retainedNumber, exact: true })).toHaveValue(retained.text);
  await expect(editor.getByText("原段删除目标文字。", { exact: false })).toHaveCount(0);
  const addition = reloaded.blocks.find((block: { id: string }) => block.id === "added:" + draft.additionId); expect(addition.text).toContain("保留的新增条款内容。");
  const reloadedTables = editor.getByRole("region", { name: "合同正文表格", exact: true }); await expect(reloadedTables).toHaveCount(2);
  for (const table of await reloadedTables.all()) await expect(table.getByRole("button", { name: "删除普通条款", exact: true })).toHaveCount(0);
  const amount = reloadedTables.nth(0).getByRole("table").getByRole("row").nth(1).getByRole("cell").nth(7); await expect(amount).toHaveText("6.5000"); await expect(amount.getByRole("textbox")).toHaveCount(0);
  const dimensions = await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth })); expect(dimensions.documentWidth).toBeLessThanOrEqual(dimensions.viewport + 1);
  await page.screenshot({ path: testInfo.outputPath("original-paragraph-deleted.png"), fullPage: true }); await writeFile(testInfo.outputPath("public-original-deletion-saved.json"), JSON.stringify({ before, facts, after, saved, reloaded, dimensions, sourceProof }, null, 2));
});
